    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
 String nama = jTextField2.getText().trim();
    String jenis = jComboBox1.getSelectedItem().toString();
    String status = jComboBox2.getSelectedItem().toString();
    String satuan = jComboBox3.getSelectedItem().toString();

    int harga;
    try {
        String clean = jTextField4.getText().replace(",", "");
    harga = Integer.parseInt(clean);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Harga harus angka");
        return;
    }

    try (Connection conn = DatabaseConnection.getConnection()) {

        String sql = "UPDATE produk SET nama_produk=?, jenis=?, satuan=?, harga=?, status=? WHERE id_produk=?";
        PreparedStatement pst = conn.prepareStatement(sql);

        pst.setString(1, nama);
        pst.setString(2, jenis);
        pst.setString(3, satuan);
        pst.setInt(4, harga);
        pst.setString(5, status);
        pst.setInt(6, idProduk);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Data berhasil diupdate");

        parent.loadTable();
        parent.setEnabled(true);
        this.dispose();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }//GEN-LAST:event_jButton1ActionPerformed

