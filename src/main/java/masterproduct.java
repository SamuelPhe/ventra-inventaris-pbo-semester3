class WrapTextRenderer extends JTextArea implements TableCellRenderer {

    public WrapTextRenderer() {
        setLineWrap(true);
        setWrapStyleWord(true);
        setOpaque(true);
    }

    @Override
    public Component getTableCellRendererComponent(
            JTable table, Object value, boolean isSelected,
            boolean hasFocus, int row, int column) {

        setText(value == null ? "" : value.toString());
        setFont(table.getFont());

        if (isSelected) {
            setBackground(table.getSelectionBackground());
            setForeground(table.getSelectionForeground());
        } else {
            setBackground(table.getBackground());
            setForeground(table.getForeground());
        }

        // auto adjust tinggi row
        setSize(table.getColumnModel().getColumn(column).getWidth(), getPreferredSize().height);
        if (table.getRowHeight(row) != getPreferredSize().height) {
            table.setRowHeight(row, getPreferredSize().height);
        }

        return this;
    }
}

    
    class HargaRenderer extends DefaultTableCellRenderer {

    private final NumberFormat nf =
        NumberFormat.getInstance(new Locale("id", "ID"));

    @Override
    public void setValue(Object value) {
        if (value == null) {
            setText("");
            return;
        }

        try {
            long harga = ((Number) value).longValue();
            setText(nf.format(harga));
        } catch (Exception e) {
            setText(value.toString());
        }

        setHorizontalAlignment(SwingConstants.RIGHT);
    }
}

    
