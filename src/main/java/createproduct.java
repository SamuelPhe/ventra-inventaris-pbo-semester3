    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
String kode = jTextField1.getText().trim();
String nama = jTextField2.getText().trim();
String jenis = jComboBox1.getSelectedItem().toString();
String status = jComboBox2.getSelectedItem().toString();
String satuan = jComboBox3.getSelectedItem().toString();

if (kode.isEmpty() || nama.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Kode dan Nama wajib diisi");
    return;
}

int harga;
try {
    String hargaText = jTextField4.getText().replace(".", "");
    harga = Integer.parseInt(hargaText);
} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Harga tidak valid");
    return;
}

try {
    Connection conn = DatabaseConnection.getConnection();

    String sql = "INSERT INTO produk (kode_produk, nama_produk, jenis, satuan, harga, status) VALUES (?, ?, ?, ?, ?,? )";
    PreparedStatement pst = conn.prepareStatement(sql);

pst.setString(1, kode);
pst.setString(2, nama);
pst.setString(3, jenis);
pst.setString(4, satuan);
pst.setInt(5, harga);
pst.setString(6, status);

    pst.executeUpdate();

    JOptionPane.showMessageDialog(this, "Produk berhasil ditambahkan");
    if (parent != null) {
    parent.loadTable();
    parent.setEnabled(true);
    parent.toFront(); 
}
    this.dispose();
    


} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());


    }//GEN-LAST:event_jButton1ActionPerformed
    }
