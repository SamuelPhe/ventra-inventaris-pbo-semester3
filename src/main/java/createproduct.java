    class HargaDocumentFilter extends DocumentFilter {

    private final NumberFormat nf =
            NumberFormat.getInstance(new Locale("id", "ID"));

    @Override
    public void insertString(FilterBypass fb, int offset, String string, AttributeSet attr)
            throws BadLocationException {
        if (string == null) return;
        replace(fb, offset, 0, string, attr);
    }

    @Override
    public void replace(FilterBypass fb, int offset, int length, String text, AttributeSet attrs)
            throws BadLocationException {

        String current = fb.getDocument().getText(0, fb.getDocument().getLength());
        String before = current.substring(0, offset);
        String after = current.substring(offset + length);

        String newText = before + (text == null ? "" : text) + after;

        String digits = newText.replaceAll("[^0-9]", "");

        if (digits.isEmpty()) {
            fb.replace(0, fb.getDocument().getLength(), "", attrs);
            return;
        }

        long value = Long.parseLong(digits);
        fb.replace(0, fb.getDocument().getLength(), nf.format(value), attrs);
    }
}
    
