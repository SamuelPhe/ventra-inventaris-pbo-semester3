private void loadHeader() {
    try {
        Connection conn = DatabaseConnection.getConnection();

        String sql = """
            SELECT 
                            o.envelope_code,
                            o.tanggal,
                            u.username
                        FROM inbound o
                        LEFT JOIN user u ON u.id = o.created_by
                        WHERE o.id_inbound = ?
        """;

        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setInt(1, idInbound);
        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            IblEnvelop.setText(rs.getString("envelope_code"));
            IblTanggal.setText(rs.getDate("tanggal").toString());
            IblUser.setText(rs.getString("username"));
        }

        rs.close();
        pst.close();
        conn.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}




private void loadDetail() {
    DefaultTableModel model = new DefaultTableModel(
        new Object[]{"Produk", "Qty", "Subtotal"}, 0
    );

    try {
        Connection conn = DatabaseConnection.getConnection();

        String sql = """
            SELECT 
                p.nama_produk,
                d.qty,
                (d.qty * d.harga) AS subtotal
            FROM inbound_detail d
            JOIN produk p ON p.id_produk = d.id_produk
            WHERE d.id_inbound = ?
        """;

        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setInt(1, idInbound);
        ResultSet rs = pst.executeQuery();

        boolean adaData = false;

        while (rs.next()) {
            adaData = true;
            model.addRow(new Object[]{
                rs.getString("nama_produk"),
                rs.getInt("qty"),
                rs.getInt("subtotal")
            });
        }

        if (!adaData) {
            JOptionPane.showMessageDialog(this, "Detail inbound kosong");
        }

        jTable1.setModel(model);

        rs.close();
        pst.close();
        conn.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}







