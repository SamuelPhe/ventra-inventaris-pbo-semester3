    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
if (jTextField1.getText().trim().isEmpty() ||
        jTextArea1.getText().trim().isEmpty() ||
        jTextField2.getText().trim().isEmpty()||
        jTextField3.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(this, "Data delivery belum lengkap");
        return;
    }

    // isi object delivery
    DeliveryData d = new DeliveryData();
    d.nama = jTextField1.getText().trim();
    d.alamat = jTextArea1.getText().trim();
    d.noHp = jTextField2.getText().trim();
    d.suratJalan = jTextField3.getText().trim();
    
    parent.simpanOutbound(draft, d);
    parent.loadDeliveryLog();
    parent.loadOutboundHeader();
    
    this.dispose();        // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

