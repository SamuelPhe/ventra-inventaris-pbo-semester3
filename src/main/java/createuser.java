    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
String username = jTextField1.getText().trim();
    String password = new String(jPasswordField1.getPassword()).trim();
    String confirm = new String(jPasswordField2.getPassword()).trim();

    if (username.isEmpty() || password.isEmpty() || confirm.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Semua kolom harus diisi.",
                "Input tidak lengkap",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    if (!password.equals(confirm)) {
        JOptionPane.showMessageDialog(this,
                "Password dan konfirmasinya tidak sama.",
                "Konfirmasi gagal",
                JOptionPane.ERROR_MESSAGE);
        return;
    }

try {
    Connection conn = DatabaseConnection.getConnection();

    String sql = "INSERT INTO user (username, password) VALUES (?, ?)";
    PreparedStatement pst = conn.prepareStatement(sql);

    pst.setString(1, username);
    pst.setString(2, PasswordUtil.hash(password));
    pst.executeUpdate();

    JOptionPane.showMessageDialog(this, "Akun berhasil ditambahkan.");

    if (parent != null) {
        parent.loadTable();      
        parent.setEnabled(true); 
        parent.setVisible(true); 
    }

    this.dispose(); 

} catch (HeadlessException | SQLException e) {
    JOptionPane.showMessageDialog(this,
            "Gagal menambahkan akun: " + e.getMessage(),
            "Kesalahan",
            JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_jButton1ActionPerformed

