    private void LoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_LoginActionPerformed
        String username = Username.getText().trim();
        String password = new String(Pw.getPassword());
        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Username dan password wajib diisi!",
                    "Validasi", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String sql = "SELECT id, username, password FROM user WHERE username = ?";
        try (Connection conn = DatabaseConnection.getConnection();
             PreparedStatement pst = conn.prepareStatement(sql)) {
            pst.setString(1, username);
            try (ResultSet rs = pst.executeQuery()) {
                if (!rs.next() || !PasswordUtil.verify(password, rs.getString("password"))) {
                    JOptionPane.showMessageDialog(this, "Username atau password salah!",
                            "Login gagal", JOptionPane.ERROR_MESSAGE);
                    return;
                }
                int userId = rs.getInt("id");
                String accountName = rs.getString("username");
                String storedPassword = rs.getString("password");
                if (PasswordUtil.needsUpgrade(storedPassword)) {
                    try (PreparedStatement upgrade = conn.prepareStatement(
                            "UPDATE user SET password = ? WHERE id = ?")) {
                        upgrade.setString(1, PasswordUtil.hash(password));
                        upgrade.setInt(2, userId);
                        upgrade.executeUpdate();
                    }
                }
                UserSession.setUser(userId, accountName);
                new Dashboard().setVisible(true);
                this.dispose();
            }
        } catch (SQLException | IllegalStateException e) {
            JOptionPane.showMessageDialog(this,
                    "Login gagal. Periksa konfigurasi database dan coba lagi.",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_LoginActionPerformed

