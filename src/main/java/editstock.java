    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
try {
        int qtyInput = Integer.parseInt(jTextField1.getText().trim());
        String ket = jTextArea1.getText().trim();
        int stokSekarang = Integer.parseInt(jTextField3.getText());

        if (qtyInput < 1) {
            JOptionPane.showMessageDialog(this, "Qty minimal 1");
            return;
        }

        if (!rbIncrease.isSelected() && !rbDecrease.isSelected()) {
            JOptionPane.showMessageDialog(this, "Pilih Increase atau Decrease");
            return;
        }

        int qtyFinal = rbIncrease.isSelected() ? qtyInput : -qtyInput;

        if (qtyFinal < 0 && stokSekarang + qtyFinal < 0) {
            JOptionPane.showMessageDialog(this, "Stok tidak mencukupi");
            return;
        }

        if (ket.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Keterangan wajib diisi");
            return;
        }

        Connection conn = DatabaseConnection.getConnection();
        conn.setAutoCommit(false);

        String sqlAdjust = "INSERT INTO adjust_stock (id_produk, qty, keterangan, tanggal, created_by) "
                         + "VALUES (?, ?, ?, NOW(), ?)";

        PreparedStatement pst = conn.prepareStatement(sqlAdjust);
        pst.setInt(1, idProduk);
        pst.setInt(2, qtyFinal);
        pst.setString(3, ket);
        pst.setInt(4, UserSession.getUserId());
        pst.executeUpdate();

        String sqlUpdate = "UPDATE produk SET stok = stok + ? WHERE id_produk = ?";
        PreparedStatement pst2 = conn.prepareStatement(sqlUpdate);
        pst2.setInt(1, qtyFinal);
        pst2.setInt(2, idProduk);
        pst2.executeUpdate();

        conn.commit();
        conn.close();

        JOptionPane.showMessageDialog(this, "Adjust stock berhasil");
        
        dispose();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Qty harus berupa angka");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }        // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

